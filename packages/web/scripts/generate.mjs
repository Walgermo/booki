#!/usr/bin/env node
/**
 * Generates @booki-aui/web: one Web Components module per Booki control.
 *
 * Every control is one framework-free definition in @booki-aui/primitives. React
 * renders it with its own `createParts`; this script reads which element each
 * React part is (input, select, button, or a plain element) and maps the same
 * parts to custom elements, so the two can never drift apart. Run it after
 * changing a control's parts:
 *
 *   node packages/web/scripts/generate.mjs
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** Writes only when the content differs, so an unchanged file keeps its mtime and its build stays current. */
function writeIfChanged(file, content) {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return;
  writeFileSync(file, content);
}

const here = path.dirname(fileURLToPath(import.meta.url));
const reactSrc = path.resolve(here, "../../react/src");
const out = path.resolve(here, "../src");
mkdirSync(out, { recursive: true });

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const FIELD = new Set(["input", "select", "textarea"]);

const controls = [];
for (const file of readdirSync(reactSrc).sort()) {
  if (!file.endsWith(".tsx") || file.includes(".test.")) continue;
  const source = readFileSync(path.join(reactSrc, file), "utf8");
  // The tags are a const beside the call (`const TAGS = { … } as const; createParts(x, TAGS)`), or inline.
  const named = source.match(/const TAGS = \{([\s\S]*?)\} as const;[\s\S]*?createParts\((\w+), TAGS\)/);
  const inline = source.match(/createParts\((\w+),\s*\{([\s\S]*?)\}\);/);
  const call = named ? [named[0], named[2], named[1]] : inline;
  if (!call) continue;
  const [, definition, body] = call;
  const stem = file.replace(/\.tsx$/, "");
  // Where the definition lives now: @booki-aui/primitives/<stem>.
  const imported = new RegExp(
    `import\\s*\\{[^}]*\\b${definition}\\b[^}]*\\}\\s*from\\s*"@booki-aui/primitives/([\\w-]+)"`,
  ).exec(source);
  const module = imported ? imported[1] : stem;
  const name = /name:\s*"([\w-]+)"/.exec(source)?.[1];
  const parts = [...body.matchAll(/(\w+):\s*"(\w+)"/g)].map(([, slot, element]) => ({ slot, element }));
  if (!parts.some((part) => part.slot === "root")) continue;
  controls.push({ stem, module, definition, name, parts });
}

for (const control of controls) {
  // Tags follow the control's file name, which is also its React entry: booki-amount-field, booki-amount-field-input.
  const base = `booki-${control.stem}`;
  const entries = control.parts.map(({ slot, element }) => {
    const tag = slot === "root" ? base : `${base}-${kebab(slot)}`;
    if (FIELD.has(element))
      return `  ${slot}: { tag: "${tag}", target: wrappedChild("${element}"), display: "contents" },`;
    if (element === "button") return `  ${slot}: { tag: "${tag}", target: wrappedButton, display: "contents" },`;
    return `  ${slot}: "${tag}",`;
  });
  const needs = new Set(["createParts"]);
  if (entries.some((e) => e.includes("wrappedChild"))) needs.add("wrappedChild");
  if (entries.some((e) => e.includes("wrappedButton"))) needs.add("wrappedButton");
  const pascal = control.stem.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
  writeIfChanged(
    path.join(out, `${control.stem}.ts`),
    `// Generated by scripts/generate.mjs from @booki-aui/react's parts. Do not edit.
import { ${[...needs].sort().join(", ")} } from "@ui-sdk/web";
import { ${control.definition} } from "@booki-aui/primitives/${control.module}";

/**
 * <${base}> and its parts. Importing this module registers the tags. Same
 * state, actions and agent bridge as the React control.
 */
export const ${pascal}Elements: Record<string, CustomElementConstructor | undefined> = createParts(${control.definition}, {
${entries.join("\n")}
});
`,
  );
}

writeIfChanged(
  path.join(out, "index.ts"),
  `// Generated by scripts/generate.mjs. Importing this module registers every Booki tag.
${controls.map((c) => `export * from "./${c.stem}.js";`).join("\n")}
export * from "./agent.js";
export * from "./agent-cursor.js";
`,
);

writeIfChanged(
  path.join(here, "../entries.json"),
  `${JSON.stringify(
    controls.map((c) => c.stem),
    null,
    2,
  )}\n`,
);

console.log(`Generated ${controls.length} controls into packages/web/src.`);
