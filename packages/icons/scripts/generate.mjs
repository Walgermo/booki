// Turns the built SVGs (written next to this package.json by the draw-icons `build`
// from source/) into lib/index.js with each icon's markup, and lib/react.js
// with an <Icon name="…" /> component. The outputs are committed, so the package
// needs no build step of its own. Run after drawing: `pnpm --filter @booki-aui/icons generate`.
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const built = readdirSync(root)
  .filter((file) => file.endsWith(".svg"))
  .sort();

/** The markup inside an SVG's root element. */
function innerOf(svg) {
  const open = /^<svg\b[^>]*>/.exec(svg);
  if (!open) throw new Error("Not an SVG");
  return svg.slice(open[0].length, svg.lastIndexOf("</svg>"));
}

mkdirSync(join(root, "lib"), { recursive: true });

const icons = {};
for (const file of built) {
  const name = file.slice(0, -4);
  const svg = readFileSync(join(root, file), "utf8").trim();
  icons[name] = innerOf(svg);
}
const names = Object.keys(icons);

const header = "// Generated by scripts/generate.mjs from the built SVGs. Do not edit.\n";
writeFileSync(
  join(root, "lib", "index.js"),
  `${header}
/** The attributes every icon's root <svg> carries: 24 grid, 1.5 stroke, in the text colour. */
export const iconAttributes = {
  xmlns: "http://www.w3.org/2000/svg",
  viewBox: "0 0 24 24",
  fill: "none",
  stroke: "currentColor",
  "stroke-width": "1.5",
  "stroke-linecap": "round",
  "stroke-linejoin": "round",
};

/** Each icon's inner markup, by name. */
export const icons = ${JSON.stringify(icons, null, 2)};

/** Every icon name. */
export const iconNames = Object.keys(icons);

/** One icon as a complete SVG string, at a size in px (16 and 20 are the sizes it is drawn for). */
export function iconSvg(name, size = 16) {
  const inner = icons[name];
  if (inner === undefined) throw new Error(\`No icon "\${name}". Icons: \${iconNames.join(", ")}.\`);
  const attrs = Object.entries({ ...iconAttributes, width: String(size), height: String(size), "aria-hidden": "true" })
    .map(([key, value]) => \`\${key}="\${value}"\`)
    .join(" ");
  return \`<svg \${attrs}>\${inner}</svg>\`;
}
`,
);
writeFileSync(
  join(root, "lib", "index.d.ts"),
  `${header}
export type IconName =
${names.map((name) => `  | ${JSON.stringify(name)}`).join("\n")};
export declare const iconAttributes: Record<string, string>;
export declare const icons: Record<IconName, string>;
export declare const iconNames: IconName[];
export declare function iconSvg(name: IconName, size?: 16 | 20): string;
`,
);
writeFileSync(
  join(root, "lib", "react.js"),
  `${header}
import { createElement } from "react";
import { icons } from "./index.js";

/**
 * A Booki icon. Decorative by default (aria-hidden); pass \`aria-label\` and
 * \`role="img"\` when the icon is the only thing that names a control.
 */
export function Icon({ name, size = 16, ...props }) {
  const inner = icons[name];
  if (inner === undefined) return null;
  return createElement("svg", {
    xmlns: "http://www.w3.org/2000/svg",
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 1.5,
    strokeLinecap: "round",
    strokeLinejoin: "round",
    "aria-hidden": props["aria-label"] ? undefined : true,
    focusable: "false",
    "data-icon": name,
    ...props,
    dangerouslySetInnerHTML: { __html: inner },
  });
}
`,
);
writeFileSync(
  join(root, "lib", "react.d.ts"),
  `${header}
import type { SVGProps } from "react";
import type { IconName } from "./index.js";

export type { IconName } from "./index.js";
export type IconProps = Omit<SVGProps<SVGSVGElement>, "children" | "dangerouslySetInnerHTML"> & {
  name: IconName;
  /** In px. The icons are drawn for 16 and 20. */
  size?: 16 | 20;
};
export declare function Icon(props: IconProps): import("react").JSX.Element | null;
`,
);
// In the repository's own format, so the format check passes on what this writes.
execFileSync("pnpm", ["exec", "biome", "format", "--write", join(root, "lib")], { cwd: root, stdio: "ignore" });
console.log(`${names.length} icons → lib/index.js, lib/react.js`);
