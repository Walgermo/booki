const tick = "`";
const coverage = [
  "<!-- Generated by scripts/generate.mjs from categories.json and the sources' aliases. Do not edit. -->",
  "",
  "# What the icons cover",
  "",
  `${names.length} icons for accounting and auditing UI, by theme. "Stands for" is what each icon means in`,
  `Booki (its ${tick}data-aliases${tick}), and what the search on booki.dev/docs/icons finds it by. Missing a use`,
  `case? Draw the icon, add it to ${tick}categories.json${tick}, and run ${tick}pnpm icons${tick}.`,
  "",
  ...categories.flatMap((category) => [
    `## ${category.en}`,
    "",
    "| Icon | Stands for |",
    "| --- | --- |",
    ...category.icons.map(
      (name) => `| ${tick}${name}${tick} | ${aliases[name].join(", ").replaceAll("-", " ") || "—"} |`,
    ),
    "",
  ]),
].join("\n");

// In the repository's own format (Biome, through stdin), so --check compares like with like.
const lib = join(root, "lib");
const formatted = Object.fromEntries(
  Object.entries(files).map(([file, text]) => [
    file,
    execFileSync("pnpm", ["exec", "biome", "format", `--stdin-file-path=${join(lib, file)}`], {
      cwd: root,
      input: text,
      encoding: "utf8",
    }),
  ]),
);
const outputs = Object.fromEntries(Object.entries(formatted).map(([file, text]) => [join(lib, file), text]));
outputs[join(root, "COVERAGE.md")] = coverage;
const stale = Object.keys(outputs).filter((path) => {
  try {
    return readFileSync(path, "utf8") !== outputs[path];
  } catch {
    return true;
  }
});

if (check) {
  if (stale.length) {
    console.error(`Out of date: ${stale.map((path) => path.slice(root.length + 1)).join(", ")}. Run: pnpm icons`);
    process.exit(1);
  }
  console.log(`lib/ and COVERAGE.md are current: ${names.length} icons.`);
} else {
  mkdirSync(lib, { recursive: true });
  for (const [path, text] of Object.entries(outputs)) writeFileSync(path, text);
  console.log(`${names.length} icons → lib/index.js, lib/react.js, COVERAGE.md`);
}
