// Turns the built SVGs (written next to this package.json by the draw-icons `build`
// from source/) into the package's modules:
//   lib/index.js  each icon's markup, its search words, and iconSvg() for any framework
//   lib/react.js  one named component per icon (BanknoteIcon), plus <Icon name="…" />
//   COVERAGE.md   every icon by theme (categories.json) and what it stands for
// The outputs are committed, so the package needs no build step of its own.
//
//   pnpm --filter @booki-aui/icons generate          write lib/
//   pnpm --filter @booki-aui/icons generate --check  fail if lib/ is out of date
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

/** The markup inside an SVG's root element. */
function innerOf(svg) {
  const open = /^<svg\b[^>]*>/.exec(svg);
  if (!open) throw new Error("Not an SVG");
  return svg.slice(open[0].length, svg.lastIndexOf("</svg>"));
}

/** `chart-bar-stacked` → `ChartBarStackedIcon`. */
export function componentName(name) {
  return `${name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase())}Icon`;
}

const names = readdirSync(root)
  .filter((file) => file.endsWith(".svg"))
  .map((file) => file.slice(0, -4))
  .sort();
const icons = {};
const aliases = {};
for (const name of names) {
  icons[name] = innerOf(readFileSync(join(root, `${name}.svg`), "utf8").trim());
  const source = readFileSync(join(root, "source", `${name}.svg`), "utf8");
  aliases[name] = (/data-aliases="([^"]*)"/.exec(source)?.[1] ?? "").split(/\s+/).filter(Boolean);
}

// Every icon sits in exactly one theme; the Icons page and COVERAGE.md are grouped by them.
const categories = JSON.parse(readFileSync(join(root, "categories.json"), "utf8"));
const listed = categories.flatMap((category) => category.icons);
const twice = listed.filter((name, i) => listed.indexOf(name) !== i);
const unknown = listed.filter((name) => !icons[name]);
const unlisted = names.filter((name) => !listed.includes(name));
const problems = [
  twice.length && `listed twice in categories.json: ${twice.join(", ")}`,
  unknown.length && `in categories.json but not drawn: ${unknown.join(", ")}`,
  unlisted.length && `drawn but in no category (add them to categories.json): ${unlisted.join(", ")}`,
].filter(Boolean);
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

