#!/usr/bin/env node
/**
 * Generates @booki-aui/vue, @booki-aui/svelte and @booki-aui/solid from the same source as
 * @booki-aui/react: each control's framework-free definition in @booki-aui/primitives
 * and the parts React maps it to. Every framework's `createParts` takes the
 * same map, so the packages can never drift apart from React.
 *
 *   node scripts/generate-frameworks.mjs
 *
 * Each control becomes a namespace of parts: `AmountField.Root`,
 * `AmountField.Input`, `AmountField.Currency`, like `createParts` returns them.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** Writes only when the content differs, so an unchanged file keeps its mtime and its build stays current. */
function writeIfChanged(file, content) {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return;
  writeFileSync(file, content);
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const reactSrc = path.join(root, "packages/react/src");
const VERSION = JSON.parse(readFileSync(path.join(root, "packages/primitives/package.json"), "utf8")).peerDependencies[
  "@ui-sdk/core"
];

const FRAMEWORKS = [
  {
    id: "vue",
    name: "Vue",
    keywords: ["vue", "vue3"],
    about: "Vue 3 components",
    libs: { vue: "^3.5.0" },
    partType: { from: "vue", name: "Component" },
  },
  {
    id: "svelte",
    name: "Svelte",
    keywords: ["svelte", "svelte5"],
    about: "Svelte components",
    libs: { svelte: "^5.33.0" },
    partType: { from: "svelte", name: "Component<any>" },
    note: "Load it through Vite with the Svelte plugin (SvelteKit has it), as with any Svelte component library.",
  },
  {
    id: "solid",
    name: "Solid",
    keywords: ["solid", "solidjs"],
    about: "Solid components",
    libs: { "solid-js": "^2.0.0", "@solidjs/web": "^2.0.0" },
    partType: { from: "solid-js", name: "Component<any>" },
  },
];

const controls = [];
for (const file of readdirSync(reactSrc).sort()) {
  if (!file.endsWith(".tsx") || file.includes(".test.")) continue;
  const source = readFileSync(path.join(reactSrc, file), "utf8");
  // The tags are a const beside the call (`const TAGS = { … } as const; createParts(x, TAGS)`), or inline.
  const named = source.match(/const TAGS = (\{[\s\S]*?\}) as const;[\s\S]*?createParts\((\w+), TAGS\)/);
  const call = named ? [named[0], named[2], named[1]] : source.match(/createParts\((\w+),\s*(\{[\s\S]*?\})\);/);
  if (!call || !/root:/.test(call[2])) continue;
  const [, definition, map] = call;
  const stem = file.replace(/\.tsx$/, "");
  const imported = new RegExp(
    `import\\s*\\{[^}]*\\b${definition}\\b[^}]*\\}\\s*from\\s*"@booki-aui/primitives/([\\w-]+)"`,
  ).exec(source);
  controls.push({ stem, module: imported ? imported[1] : stem, definition, map });
}

const pascal = (stem) => stem.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

for (const fw of FRAMEWORKS) {
  const dir = path.join(root, "packages", fw.id);
  const src = path.join(dir, "src");
  mkdirSync(src, { recursive: true });

  for (const control of controls) {
    writeIfChanged(
      path.join(src, `${control.stem}.ts`),
      `// Generated by scripts/generate-frameworks.mjs from @booki-aui/react's parts. Do not edit.
import { createParts, type Parts } from "@ui-sdk/${fw.id}/primitive";
import { ${control.definition} } from "@booki-aui/primitives/${control.module}";

const parts = ${control.map} as const;

/** ${pascal(control.stem)}'s parts for ${fw.name}: the same state, actions and agent bridge as in React. */
export const ${pascal(control.stem)}: Parts<typeof ${control.definition}, typeof parts> = createParts(${control.definition}, parts);
`,
    );
  }

  writeIfChanged(
    path.join(src, "agent.ts"),
    `// Generated by scripts/generate-frameworks.mjs. Do not edit.
import { bookiAllow, bookiRegisterTools, type AgentDecision, type AgentPolicyOptions } from "@booki-aui/primitives/agent-policy";
export { actAndRecord, withRecordedAct } from "@booki-aui/primitives/agent-policy";
import { createAgent, registerTools as registerBridgeTools } from "@ui-sdk/${fw.id}/agent";

export type BookiAgent = ReturnType<typeof createAgent>;

export type CreateBookiAgentOptions = AgentPolicyOptions & {
  /** How long a step waits for \`allow\`, in ms. */
  timeout?: number;
};

/**
 * The agent bridge for Booki's ${fw.name} parts, with the same rules as
 * @booki-aui/react: a marked step runs only on a yes from \`allow\`, and a person's
 * decision (approve, sign, release) is refused whatever \`allow\` says.
 */
export function createBookiAgent(options: CreateBookiAgentOptions = {}): BookiAgent {
  const { timeout } = options;
  const allow = bookiAllow(options);
  return createAgent(allow ? { timeout, allow } : { timeout });
}

/** Registers the agent's tools with the browser's own agent (WebMCP), with the same rules. */
export const registerTools: (
  agent: BookiAgent,
  options: AgentPolicyOptions & { allow: NonNullable<AgentPolicyOptions["allow"]> },
) => () => void = bookiRegisterTools(registerBridgeTools);

export type { AgentDecision };
`,
  );

  writeIfChanged(
    path.join(src, "index.ts"),
    `// Generated by scripts/generate-frameworks.mjs. Do not edit.
${controls.map((c) => `export * from "./${c.stem}.js";`).join("\n")}
export * from "./agent.js";
`,
  );

  const pkgFile = path.join(dir, "package.json");
  const existing = existsSync(pkgFile) ? JSON.parse(readFileSync(pkgFile, "utf8")) : {};
  const pkg = {
    name: `@booki-aui/${fw.id}`,
    version: existing.version ?? "0.1.0",
    description: `Booki for ${fw.name} (experimental) — agent-first accounting controls as ${fw.about}: the same rules, state and agent actions as @booki-aui/react.`,
    type: "module",
    license: "MIT",
    repository: {
      type: "git",
      url: "git+https://github.com/Walgermo/booki.git",
      directory: `packages/${fw.id}`,
    },
    homepage: "https://github.com/Walgermo/booki#readme",
    keywords: ["accounting", "agents", ...fw.keywords, "voucher", "invoice"],
    sideEffects: false,
    files: ["dist", "CHANGELOG.md"],
    main: "./dist/index.js",
    types: "./dist/index.d.ts",
    exports: {
      ".": { types: "./dist/index.d.ts", default: "./dist/index.js" },
      "./*": { types: "./dist/*.d.ts", default: "./dist/*.js" },
    },
    scripts: { build: "tsup", typecheck: "tsc --noEmit" },
    dependencies: { "@booki-aui/core": "workspace:*", "@booki-aui/primitives": "workspace:*" },
    // The ranges @ui-sdk/<framework> itself asks for.
    peerDependencies: { "@ui-sdk/core": VERSION, [`@ui-sdk/${fw.id}`]: VERSION, ...fw.libs },
    devDependencies: {
      "@ui-sdk/core": VERSION,
      [`@ui-sdk/${fw.id}`]: VERSION,
      ...fw.libs,
      tsup: "^8.5.0",
      typescript: "^5.9.3",
    },
    publishConfig: { access: "public" },
  };
  writeIfChanged(pkgFile, `${JSON.stringify(pkg, null, 2)}\n`);
  writeIfChanged(path.join(dir, "LICENSE"), readFileSync(path.join(root, "LICENSE"), "utf8"));

  writeIfChanged(
    path.join(dir, "tsup.config.ts"),
    `import { defineConfig } from "tsup";

export default defineConfig({
  entry: ["src/index.ts", "src/agent.ts", ${controls.map((c) => `"src/${c.stem}.ts"`).join(", ")}],
  format: ["esm"],
  // Types from the built @booki-aui/primitives: the exports carry explicit types, so nothing private is named.
  dts: { compilerOptions: { paths: {} } },
  splitting: true,
  clean: true,
  sourcemap: true,
  target: "es2022",
  // Explicit names: the declaration build ignores a regex here.
  external: ["@booki-aui/core", "@booki-aui/primitives", ${controls.map((c) => `"@booki-aui/primitives/${c.module}"`).join(", ")}, "@ui-sdk/core", "@ui-sdk/${fw.id}", "@ui-sdk/${fw.id}/primitive", "@ui-sdk/${fw.id}/agent", "vue", "svelte", "solid-js", "@solidjs/web"],
});
`,
  );
  writeIfChanged(
    path.join(dir, "tsconfig.json"),
    `${JSON.stringify(
      {
        extends: "../../tsconfig.base.json",
        compilerOptions: {
          outDir: "dist",
          noEmit: true,
          // As in @booki-aui/react: read the definitions' types from source, since their
          // inferred types name ui-sdk internals a built .d.ts can only copy.
          paths: {
            "@booki-aui/primitives": ["../primitives/src/index.ts"],
            "@booki-aui/primitives/*": ["../primitives/src/*.ts"],
          },
        },
        include: ["src"],
      },
      null,
      2,
    )}\n`,
  );
  writeIfChanged(
    path.join(dir, "README.md"),
    `# @booki-aui/${fw.id}

Experimental. This adapter is less tested than \`@booki-aui/react\`, and its API may
change between releases. See the
[Support section](https://github.com/Walgermo/booki#support) of the README.

Agent-first accounting controls for ${fw.name}. The same rules, state and agent
actions as \`@booki-aui/react\`, generated from the same framework-free definitions
in \`@booki-aui/primitives\`.

\`\`\`bash
booki_version=$(npm view @booki-aui/${fw.id}@latest version) &&
ui_sdk_version=$(npm view "@booki-aui/${fw.id}@$booki_version" peerDependencies.@ui-sdk/core) &&
pnpm add --save-exact "@booki-aui/${fw.id}@$booki_version" "@booki-aui/styles@$booki_version" \\
  "@ui-sdk/core@$ui_sdk_version" "@ui-sdk/${fw.id}@$ui_sdk_version"
\`\`\`

Each control is a namespace of parts, like \`AmountField.Root\` and
\`AmountField.Input\`. Create the agent bridge once with \`createBookiAgent\`.
Peer dependencies: \`@ui-sdk/core\` and \`@ui-sdk/${fw.id}\` ${VERSION}.
${fw.note ? `\n${fw.note}\n` : ""}`,
  );
}

console.log(`Generated ${controls.length} controls for ${FRAMEWORKS.map((f) => f.name).join(", ")}.`);
